public class SequentialProgramStructureFibonacciSequence {
    public static void main(String[] args) {

        int a = 1;
        int b = 1;
        System.out.println("Fibonacci Sequence:");
        System.out.print(a + " ");
        System.out.print(b + " ");
        int c = a + b;
        System.out.print(c + " ");
        int d = b + c;
        System.out.print(d + " ");
        int e = c + d;
        System.out.print(e + " ");
        int f = d + e;
        System.out.print(f + " ");
        int g = e + f;
        System.out.print(g + " ");
        int h = f + g;
        System.out.print(h + " ");
        int i = g + h;
        System.out.print(i + " ");
        int j = h + i;
        System.out.print(j + " ");
    }
}